#!/usr/bin/env python3
"""mac_libm_slots.h: GameAssembly.dylib 25846389 (arm64) pointer slots (__la_symbol_ptr / __got) bound to libm
symbols, so math_mac.c can point them at the dsm_ functions. Re-run for a new build."""
import os, lief, re
P = os.path.expanduser("~/ds_skill_truth/GA_arm64_25846389.dylib")
b = lief.parse(P)
WANT = re.compile(r"^_(acosf?|asinf?|atanf?|atan2f?|sinf?|cosf?|tanf?|sinhf?|coshf?|tanhf?|expf?|exp2f|logf?|log10f?|powf?|hypotf?|__sincosf?_stret)$")
rows = sorted({(bd.address, bd.symbol.name) for bd in b.bindings if bd.has_symbol and WANT.match(bd.symbol.name)})
sec = {}
for s in b.sections:
    for a, n in rows:
        if s.virtual_address <= a < s.virtual_address + s.size: sec[a] = s.name
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "mac_libm_slots.h"), "w") as f:
    f.write("/* GENERATED by gen_mac_slots.py from GameAssembly.dylib 25846389 arm64: slot rva, libm symbol */\n")
    for a, n in rows:
        f.write(f'SLOT(0x{a:X}, {n[1:]}) /* {sec.get(a, "?")} */\n')
print(len(rows), "slots;", sorted({n for _, n in rows}))
