#!/bin/zsh
# Build the Test Fights engine pieces (no game): the QuickJS objects, sg_js, sg_cache and the test tools.
# Output in <repo>/build_c4/ (git-ignored). usage: custom/fights/build.sh [win]   (win = llvm-mingw cross compile check)
set -e
H=${0:A:h}; R=${H:h:h}; B=$R/build_c4; mkdir -p $B/obj $B/objwin
# the two JS files the engine embeds -> sg_embed.h
python3 - $H $B <<'EOF'
import sys, os
h, b = sys.argv[1], sys.argv[2]
out = ['/* generated by custom/fights/build.sh from sg_prelude.js and sg_glue.js - do not edit */']
for name in ('sg_prelude', 'sg_glue'):
    data = open(os.path.join(h, name + '.js'), 'rb').read()
    out.append('static const unsigned char %s_js[] = {' % name)
    for i in range(0, len(data), 24):
        out.append(' ' + ','.join(str(x) for x in data[i:i+24]) + ',')
    out.append(' 0 };')
    out.append('static const unsigned int %s_js_len = %d;' % (name, len(data)))
open(os.path.join(b, 'sg_embed.h'), 'w').write('\n'.join(out) + '\n')
EOF
QJS=(quickjs cutils dtoa libregexp libunicode)
QDEF=(-D_GNU_SOURCE -DCONFIG_VERSION=\"$(cat $H/quickjs/VERSION)\")
CC=${CC:-clang}
if [[ $1 == win ]]; then
  TC=~/tools/llvm-mingw/bin/x86_64-w64-mingw32-clang
  for f in $QJS; do
    [[ $B/objwin/$f.o -nt $H/quickjs/$f.c ]] || nice -n 19 $TC -O2 -fwrapv $QDEF -D__USE_MINGW_ANSI_STDIO -w -c $H/quickjs/$f.c -o $B/objwin/$f.o
  done
  nice -n 19 $TC -O2 -c $H/tinf/tinflate.c -o $B/objwin/tinflate.o
  nice -n 19 $TC -O2 -Wall -I$B -c $H/sg_js.c -o $B/objwin/sg_js.o
  nice -n 19 $TC -O2 -Wall -c $H/cm_http.c -o $B/objwin/cm_http.o
  nice -n 19 $TC -O2 -Wall -c $H/sg_cache.c -o $B/objwin/sg_cache.o
  nice -n 19 $TC -O2 -Wall -c $R/custom/gallery/gallery.c -o $B/objwin/gallery.o
  echo "win objects ok: $B/objwin"
  exit 0
fi
for f in $QJS; do
  [[ $B/obj/$f.o -nt $H/quickjs/$f.c ]] || nice -n 19 $CC -O2 -fwrapv $QDEF -w -c $H/quickjs/$f.c -o $B/obj/$f.o &
done
wait
$CC -O2 -c $H/tinf/tinflate.c -o $B/obj/tinflate.o
$CC -O2 -Wall -Wextra -Wno-unused-parameter -I$B -c $H/sg_js.c -o $B/obj/sg_js.o
$CC -O2 -Wall -Wextra -Wno-unused-parameter -c $H/cm_http.c -o $B/obj/cm_http.o
$CC -O2 -Wall -Wextra -Wno-unused-parameter -c $H/sg_cache.c -o $B/obj/sg_cache.o
$CC -O2 -Wall -c $R/src/fe/fe_json.c -o $B/obj/fe_json.o
QOBJ=($B/obj/{quickjs,cutils,dtoa,libregexp,libunicode,tinflate}.o)
$CC -O2 -Wall -o $B/sg_cli $H/test/sg_cli.c $B/obj/sg_js.o $B/obj/fe_json.o $QOBJ -lm
$CC -O2 -Wall -o $B/sg_cache_test $H/test/sg_cache_test.c $B/obj/sg_cache.o $B/obj/cm_http.o $B/obj/sg_js.o $B/obj/fe_json.o $QOBJ -lm
$CC -O2 -Wall -Wextra -Wno-unused-parameter -c $R/custom/gallery/gallery.c -o $B/obj/gallery.o
$CC -O2 -Wall -o $B/gal_test $R/custom/gallery/test/gal_test.c $B/obj/gallery.o $B/obj/cm_http.o $B/obj/fe_json.o -lm
echo "built: $B/sg_cli $B/sg_cache_test $B/gal_test"
