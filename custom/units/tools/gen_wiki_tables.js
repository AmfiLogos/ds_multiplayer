// Emits custom/units/pvp_wiki_tables.h: the DS wiki builder's share-link index tables (same order and fingerprint as builder.js
// dsbIdx), for the C decoder. Run when the wiki data changes:  node custom/units/tools/gen_wiki_tables.js > custom/units/pvp_wiki_tables.h
const c = require('./wiki_codec_probe.js').load(), D = c.D, X = c.dsbIdx();
const q = s => JSON.stringify(String(s));
const arr = (name, a) => `static const char *const ${name}[${Math.max(a.length, 1)}] = { ${a.length ? a.map(q).join(', ') : '0'} };\n#define ${name}_N ${a.length}\n`;
let out = `/* GENERATED by ext/pvp/tools/gen_wiki_tables.js from ~/dungeonsettlersdb/site/builder/data.js. Do not edit. */\n#pragma once\n`;
out += `#define WK_FP ${X.fp}\n`;
for (const [n, a] of [['WK_RACE', X.RACE], ['WK_BG', X.BG], ['WK_IND', X.IND], ['WK_INSC', X.INSC], ['WK_TREE', X.TREE], ['WK_SKILL', X.SKILL],
                      ['WK_ITEM', X.ITEM], ['WK_STAT', X.STAT], ['WK_SLOT', X.SLOT], ['WK_SOUL', X.SOUL], ['WK_ACQ', X.ACQ], ['WK_MAJ', D.majors], ['WK_TIER', D.tiers.order]])
  out += arr(n, a);
// item tags (rolled affixes): per item in WK_ITEM order: tag count, then (lo, hi) per tag
const tags = X.ITEM.map(k => (D.items[k].tags || []).map(t => [t[1], t[2]]));
out += `static const unsigned char WK_ITEM_NTAGS[${X.ITEM.length}] = { ${tags.map(t => t.length).join(', ')} };\n`;
const flat = []; const at = []; tags.forEach(t => { at.push(flat.length / 2); t.forEach(p => flat.push(p[0], p[1])); });
out += `static const unsigned short WK_ITEM_TAG_AT[${X.ITEM.length}] = { ${at.join(', ')} };\n`;
out += `static const double WK_TAG_RANGE[${Math.max(flat.length, 2)}] = { ${flat.length ? flat.map(v => String(+v)).join(', ') : '0'} };\n`;
// portraits per race (index into the race's pool)
const P = D.portraits || {};
out += `static const char *const *const WK_PORTRAITS[${X.RACE.length}] = { ${X.RACE.map((r, i) => P[r] ? `WK_PORT_${i}` : '0').join(', ')} };\n`.replace(/^/, X.RACE.map((r, i) => P[r] ? arr(`WK_PORT_${i}`, P[r]) : '').join(''));
out += `static const int WK_PORTRAITS_N[${X.RACE.length}] = { ${X.RACE.map(r => (P[r] || []).length).join(', ')} };\n`;
// conditions (hunger / exhaustion groups): options per group
const CG = D.cond || [];
out += CG.map((g, i) => arr(`WK_COND_${i}`, g.opts.map(o => o.k))).join('');
out += `static const char *const *const WK_COND[${Math.max(CG.length, 1)}] = { ${CG.length ? CG.map((g, i) => `WK_COND_${i}`).join(', ') : '0'} };\n#define WK_COND_N ${CG.length}\n`;
out += `static const int WK_COND_OPTS[${Math.max(CG.length, 1)}] = { ${CG.length ? CG.map(g => g.opts.length).join(', ') : '0'} };\n`;
// retired entries (D.retired): the builder decodes a retired race as its default race (Human) and drops retired traits
const RET = D.retired || {};
out += `static const signed char WK_RACE_RETIRED[${X.RACE.length}] = { ${X.RACE.map(r => (RET.races || {})[r] ? 1 : 0).join(', ')} };\n`;
out += `#define WK_RACE_DEFAULT ${X.RACE.indexOf('AFFECTER_Human')}\n`;
out += `static const signed char WK_IND_RETIRED[${X.IND.length}] = { ${X.IND.map(k => (RET.ind || {})[k] ? 1 : 0).join(', ')} };\n`;
process.stdout.write(out);
