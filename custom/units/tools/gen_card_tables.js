// Tables for the Compact Plus card (custom/units/mu_card.c), generated from the wiki builder's own data
// (~/dungeonsettlersdb/site/builder/data.js + builder.js, loaded by test/node/builder_ref.js). Indices are the link
// index spaces of pvp_wiki_tables.h (WK_*), so a decoded wk_build reads them directly; MUC_FP must equal WK_FP.
// Skills: the combined space MUC_SK = WK_SKILL, then the item / tree skills a link cannot name (basic attacks...).
//   node custom/units/tools/gen_card_tables.js > custom/units/mu_card_tables.h
const path = require('path');
const c = require(path.join(__dirname, '..', 'test', 'node', 'builder_ref.js')).load(), D = c.D, X = c.dsbIdx();
const out = [];
const q = s => s == null ? '0' : JSON.stringify(String(s));
const arr = (type, name, vals, n) => out.push(`static const ${type} ${name}[${n == null ? vals.length || 1 : n}] = { ${vals.length ? vals.join(', ') : '0'} };`);

const SK = X.SKILL.slice(), iSK = {};
SK.forEach((k, i) => { iSK[k] = i; });
const sk = k => { if (k == null) return -1; if (!(k in iSK)) { iSK[k] = SK.length; SK.push(k); } return iSK[k]; };

// trees: kind, member skills, the tree's inscription
const treeKind = X.TREE.map(t => D.trees[t] ? (D.trees[t].kind === 'main' ? 1 : 0) : -1);
const treeSk = X.TREE.map(t => { const o = []; if (D.trees[t]) D.trees[t].rows.forEach(r => r.forEach(k => { if (k) o.push(sk(k)); })); return o; });
const treeInsc = X.TREE.map(t => { const k = c.treeInscKey(t); return k && X.INSC.indexOf(k) >= 0 ? X.INSC.indexOf(k) : -1; });
// items: basic skill, default skills, the weapon label (builder.js equippedWeaponLabel: WSUBLABEL[sub] || sub)
const ws = c.__src.match(/\nvar WSUBLABEL = (\{[\s\S]*?\});/);
const WSUB = ws ? Function('return ' + ws[1])() : {};
const itemOk = X.ITEM.map(k => D.items[k] ? 1 : 0);
const itemBsk = X.ITEM.map(k => { const it = D.items[k]; return it && it.bsk ? sk(it.bsk) : -1; });
const itemDefAt = [], itemDef = [];
X.ITEM.forEach(k => { const it = D.items[k]; itemDefAt.push(itemDef.length); ((it && it.defskills) || []).forEach(s => { if (s) itemDef.push(sk(s)); }); });
itemDefAt.push(itemDef.length);
const itemW = X.ITEM.map(k => { const it = D.items[k]; return it && it.sub ? (WSUB[it.sub] || it.sub) : null; });
// backgrounds: granted trees (builder.js bgWeaponTrees / bgSubTrees, filtered on D.trees)
const bgMains = X.BG.map(k => { const b = D.bg[k]; return b ? (b.mains || []).filter(t => D.trees[t]).map(t => X.TREE.indexOf(t)) : []; });
const bgSubs = X.BG.map(k => { const b = D.bg[k]; return b ? (b.subs || []).map(p => p[0]).filter(t => D.trees[t]).map(t => X.TREE.indexOf(t)) : []; });
if (bgMains.concat(bgSubs).some(l => l.some(i => i < 0))) throw new Error('a background tree is not in the link tree table');
const flat = ls => { const at = [], v = []; ls.forEach(l => { at.push(v.length); l.forEach(x => v.push(x)); }); at.push(v.length); return [at, v]; };
// races: rollable traits (builder.js indAvail: pool weight > 0), first portrait (firstPortrait)
const raceOk = X.RACE.map(k => D.races.some(r => r.k === k) ? 1 : 0);
const raceInd = X.RACE.map(k => { const r = D.races.find(x => x.k === k); return X.IND.map(i => r && c.poolWeight(r.ind, i) > 0 ? 1 : 0); });
const firstPort = X.RACE.map(k => { const p = (D.portraits || {})[k] || []; return p.length ? p[0] : null; });
Object.keys(D.passiveGrants).forEach(sk);   // a grant can sit on a non-learnable skill (SKILL_WeaponDeflect)
// skills of the combined space (filled last: the lines above add item / tree skills)
const skOk = () => SK.map(k => D.skills[k] ? 1 : 0), skPas = () => SK.map(k => D.skills[k] && D.skills[k].ty === 'Passive' ? 1 : 0);
const skBar = () => SK.map(k => c.barOnly(k) ? 1 : 0);
const pg = () => SK.map(k => D.passiveGrants[k]);

out.push('/* GENERATED by custom/units/tools/gen_card_tables.js from ~/dungeonsettlersdb/site/builder (data.js + builder.js). Do not edit. */');
out.push('#pragma once');
out.push('#include "pvp_wiki_tables.h"');
out.push(`#define MUC_FP ${X.fp}`);
out.push(`#define MUC_SK_N ${SK.length}`);
arr('char *const', 'MUC_SK', SK.map(q));
arr('signed char', 'MUC_SK_OK', skOk()); arr('signed char', 'MUC_SK_PASSIVE', skPas()); arr('signed char', 'MUC_SK_BARONLY', skBar());
/* passive grants: cond = folded at its maximum by the builder (owner rule); thr = a banked milestone counter */
const P = pg();
arr('signed char', 'MUC_PG', P.map(p => p ? 1 : 0)); arr('signed char', 'MUC_PG_COND', P.map(p => p && p.cond ? 1 : 0));
arr('signed char', 'MUC_PG_AFF', P.map(p => p && p.aff ? 1 : 0));
const thr = P.map(p => (p && p.thr) || []), [thrAt, thrV] = flat(thr);
arr('unsigned short', 'MUC_PG_THR_AT', thrAt); arr('double', 'MUC_PG_THR', thrV);
arr('signed char', 'MUC_TREE_KIND', treeKind, 'WK_TREE_N');
const [tsAt, tsV] = flat(treeSk); arr('unsigned short', 'MUC_TREE_SK_AT', tsAt); arr('short', 'MUC_TREE_SK', tsV);
arr('short', 'MUC_TREE_INSC', treeInsc, 'WK_TREE_N');
arr('signed char', 'MUC_INSC_OK', X.INSC.map(k => c.D.insc.some(e => e.k === k) ? 1 : 0), 'WK_INSC_N');
arr('signed char', 'MUC_IND_OK', X.IND.map(k => D.ind[k] ? 1 : 0), 'WK_IND_N');
arr('char *const', 'MUC_ACQ_KEY', X.ACQ.map(k => D.ind[k] ? q(k) : '0'), 'WK_ACQ_N');
arr('signed char', 'MUC_SOUL_OK', X.SOUL.map(k => D.souls && D.souls[k] ? 1 : 0), 'WK_SOUL_N');
arr('signed char', 'MUC_ITEM_OK', itemOk, 'WK_ITEM_N'); arr('short', 'MUC_ITEM_BSK', itemBsk, 'WK_ITEM_N');
arr('unsigned short', 'MUC_ITEM_DEF_AT', itemDefAt); arr('short', 'MUC_ITEM_DEF', itemDef);
arr('char *const', 'MUC_ITEM_WLABEL', itemW.map(q), 'WK_ITEM_N');
const [bmAt, bmV] = flat(bgMains), [bsAt, bsV] = flat(bgSubs);
arr('signed char', 'MUC_BG_OK', X.BG.map(k => D.bg[k] ? 1 : 0), 'WK_BG_N');
arr('unsigned short', 'MUC_BG_MAIN_AT', bmAt); arr('signed char', 'MUC_BG_MAIN', bmV);
arr('unsigned short', 'MUC_BG_SUB_AT', bsAt); arr('signed char', 'MUC_BG_SUB', bsV);
arr('signed char', 'MUC_RACE_OK', raceOk, 'WK_RACE_N');
out.push(`static const signed char MUC_RACE_IND[WK_RACE_N][WK_IND_N] = { ${raceInd.map(r => '{ ' + r.join(', ') + ' }').join(', ')} };`);
arr('char *const', 'MUC_FIRST_PORTRAIT', firstPort.map(q), 'WK_RACE_N');
arr('signed char', 'MUC_SLOT_ORDER', D.slots.map(s => X.SLOT.indexOf(s)));
arr('short', 'MUC_PG_ORDER', Object.keys(D.passiveGrants).map(k => iSK[k]));   /* stackPassives walks D.passiveGrants in key order */
out.push(`#define MUC_PG_ORDER_N ${Object.keys(D.passiveGrants).length}`);
out.push(`#define MUC_SLOT_ORDER_N ${D.slots.length}`);
out.push(`#define MUC_QUICK_SLOTS ${c.quickSlotCount()}`);
out.push(`#define MUC_BANKED_NEEDS_SKILL ${D.consts.bankedNeedsSkill ? 1 : 0}`);
process.stdout.write(out.join('\n').replace(/static const char \*const/g, 'static const char *const') + '\n');
